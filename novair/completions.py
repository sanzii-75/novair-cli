"""Shell completion generators — `novair completions {bash,zsh,fish}`.

Like omp, scripts are generated from live metadata (subcommands, flags,
provider profiles) so they never drift from the actual CLI. Print to stdout
and wire up with `eval "$(novair completions zsh)"`.
"""
from __future__ import annotations

from typing import List

from .config import PRESETS, available_profiles

SUBCOMMANDS = ["chat", "run", "providers", "models", "sessions", "completions"]
FLAGS = [
    "--provider", "--model", "--base-url", "--api-key", "--system",
    "--temperature", "--max-tokens", "--top-p", "--yolo", "-s", "--session",
]
_TAKES_VALUE = {
    "--provider", "--model", "--base-url", "--api-key", "--system",
    "--temperature", "--max-tokens", "--top-p", "-s", "--session",
}


def _provider_names() -> List[str]:
    """Every profile the CLI would accept for --provider, detected live."""
    names = list(PRESETS.keys()) + ["default"]
    names.extend(p["name"] for p in available_profiles())
    seen: List[str] = []
    for n in names:
        if n not in seen:
            seen.append(n)
    return seen


def _script(shell: str, providers: List[str]) -> str:
    prov = " ".join(providers)
    if shell == "bash":
        return f"""\
# bash completion for novair — generated by `novair completions bash`
_novair() {{
    local cur prev
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local commands="{' '.join(SUBCOMMANDS)}"
    local flags="{' '.join(FLAGS)}"
    local providers="{prov}"
    case "$prev" in
        --provider) COMPREPLY=( $(compgen -W "$providers" -- "$cur") ); return 0 ;;
        -s|--session) return 0 ;;
        --model|--base-url|--api-key|--system|--temperature|--max-tokens|--top-p) return 0 ;;
    esac
    if [[ $COMP_CWORD -eq 1 ]]; then
        COMPREPLY=( $(compgen -W "$commands $flags --version" -- "$cur") )
        return 0
    fi
    case "$cur" in
        -*) COMPREPLY=( $(compgen -W "$flags" -- "$cur") ) ;;
        *) COMPREPLY=( $(compgen -f -- "$cur") ) ;;
    esac
}}
complete -F _novair novair
"""
    if shell == "zsh":
        return f"""\
#compdef novair
# zsh completion for novair — generated by `novair completions zsh`
_novair() {{
    local -a commands
    commands=(
{''.join(f'        "{c}:novair {c}"' + chr(10) for c in SUBCOMMANDS)}    )
    local -a providers
    providers=({' '.join(providers)})
    _arguments -C \\
        '1:command:->cmds' \\
        '(--version)--version[print version]' \\
        '(--provider)--provider[provider profile]:provider:($providers)' \\
        '(--model)--model[model id]:model:' \\
        '(--base-url)--base-url[OpenAI-compatible base URL]:url:' \\
        '(--api-key)--api-key[API key]:key:' \\
        '(--system)--system[system prompt override]:text:' \\
        '(--temperature)--temperature[sampling temperature]:temp:' \\
        '(--max-tokens)--max-tokens[max completion tokens]:tokens:' \\
        '(--top-p)--top-p[nucleus sampling]:p:' \\
        '(--yolo)--yolo[skip tool confirmations]' \\
        '(-s --session)'{{-s,--session}}'[session id]:id:' \\
        '*::arg:->args'
    case $state in
        cmds)
            _describe 'command' commands ;;
        args)
            case $words[1] in
                chat|run|models) _arguments '*:flag:(--provider --model --base-url --api-key --system --temperature --max-tokens --top-p --yolo -s --session)' ;;
                sessions) _arguments '--rm[delete a session]:id:' ;;
                completions) _arguments '1:shell:(bash zsh fish)' ;;
            esac ;;
    esac
}}
compdef _novair novair
"""
    # fish
    lines = [
        "# fish completion for novair — generated by `novair completions fish`",
        "complete -c novair -f",
    ]
    for c in SUBCOMMANDS:
        lines.append(f"complete -c novair -n '__fish_use_subcommand' -a '{c}' -d 'novair {c}'")
    lines.append("complete -c novair -n '__fish_seen_subcommand_from completions' "
                 "-n 'not __fish_seen_subcommand_from bash zsh fish' -a 'bash zsh fish'")
    for f in FLAGS:
        if f in _TAKES_VALUE:
            lines.append(f"complete -c novair -l {f.lstrip('-')} -r")
        else:
            lines.append(f"complete -c novair -l {f.lstrip('-')}")
    lines.append("complete -c novair -l provider -r -a '" + prov + "' -d 'provider profile'")
    lines.append("complete -c novair -l version -f -d 'print version'")
    return "\n".join(lines) + "\n"


def script_for(shell: str) -> str:
    if shell not in ("bash", "zsh", "fish"):
        raise ValueError(f"unsupported shell: {shell} (use bash, zsh or fish)")
    return _script(shell, _provider_names())
